#!/usr/bin/env python3
"""Convert Lucide SVG icons into Slint `Path` components.

Slint's `Path` element takes an SVG path *command string*, but the Lucide
icons are drawn with `<path>`, `<rect>`, `<circle>` and `<line>` elements.
Only `<path>` maps directly, so this script rewrites the other three into
equivalent path commands.

Why not ship the SVGs as image resources? Because an image resource is
rasterized at build time with a fixed color. The app needs its icons to
follow the theme — a muted icon on a dark surface, a brand-red icon when a
subscription is running — and `Path` takes its `stroke` and `fill` as
properties, so one component serves every color.

The output is a `.slint` file with one component per icon, each `inherits
Path`. The icon's `commands` are the concatenation of its sub-paths, which
is fine: a `Path` can hold several disjoint sub-paths.

Usage: convert_icons.py <icons-dir> <output.slint>
"""

from __future__ import annotations

import math
import re
import sys
from pathlib import Path

# Lucide draws on a 24x24 grid.
VIEWBOX = 24.0

ELEMENT_RE = re.compile(r"<(path|rect|circle|line)\b([^>]*?)/?>", re.S)
ATTR_RE = re.compile(r'([\w:-]+)\s*=\s*"([^"]*)"')


def attrs(text: str) -> dict[str, str]:
    return {k: v for k, v in ATTR_RE.findall(text)}


def num(value: str | None, default: float = 0.0) -> float:
    if value is None:
        return default
    return float(value)


def rect_to_path(a: dict[str, str]) -> str:
    """A rounded rectangle as path commands.

    `rx` is the corner radius; `ry` defaults to `rx` when absent. A
    rectangle with no radius is four straight lines.
    """
    x = num(a.get("x"))
    y = num(a.get("y"))
    w = num(a.get("width"))
    h = num(a.get("height"))
    rx = num(a.get("rx"), 0.0)
    ry = num(a.get("ry"), rx)

    if rx <= 0 and ry <= 0:
        return f"M{x} {y} L{x + w} {y} L{x + w} {y + h} L{x} {y + h} Z"

    # A radius larger than the side would make the corners overlap; the SVG
    # spec says to scale it down instead.
    rx = min(rx, w / 2)
    ry = min(ry, h / 2)
    return (
        f"M{x + rx} {y} "
        f"L{x + w - rx} {y} "
        f"A{rx} {ry} 0 0 1 {x + w} {y + ry} "
        f"L{x + w} {y + h - ry} "
        f"A{rx} {ry} 0 0 1 {x + w - rx} {y + h} "
        f"L{x + rx} {y + h} "
        f"A{rx} {ry} 0 0 1 {x} {y + h - ry} "
        f"L{x} {y + ry} "
        f"A{rx} {ry} 0 0 1 {x + rx} {y} Z"
    )


def circle_to_path(a: dict[str, str]) -> str:
    """A circle as two half-arcs.

    An arc's endpoints have to be exactly on the circle, so the halves are
    split at the top and bottom rather than at an arbitrary point.
    """
    cx = num(a.get("cx"))
    cy = num(a.get("cy"))
    r = num(a.get("r"))
    return (
        f"M{cx - r} {cy} "
        f"A{r} {r} 0 0 1 {cx + r} {cy} "
        f"A{r} {r} 0 0 1 {cx - r} {cy} Z"
    )


def line_to_path(a: dict[str, str]) -> str:
    """A line as a move and a line-to."""
    return (
        f"M{num(a.get('x1'))} {num(a.get('y1'))} "
        f"L{num(a.get('x2'))} {num(a.get('y2'))}"
    )


def element_to_path(tag: str, raw: str) -> str | None:
    a = attrs(raw)
    if tag == "path":
        d = a.get("d")
        return d if d else None
    if tag == "rect":
        return rect_to_path(a)
    if tag == "circle":
        return circle_to_path(a)
    if tag == "line":
        return line_to_path(a)
    return None


def kebab(name: str) -> str:
    """`circle-check` -> `CircleCheck`, a valid Slint component name."""
    return "".join(part.capitalize() for part in name.split("-"))


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2

    source = Path(sys.argv[1])
    target = Path(sys.argv[2])

    icons = sorted(source.glob("*.svg"))
    if not icons:
        print(f"no icons in {source}", file=sys.stderr)
        return 1

    parts = [
        "// The icon set.",
        "//",
        "// Generated by `tools/convert_icons.py` from the Lucide icon set",
        "// (ISC licensed, https://lucide.dev). Do not edit by hand.",
        "//",
        "// Each icon is a `Path` rather than an image resource, so that the",
        "// stroke and fill follow the theme at runtime instead of being",
        "// frozen into a raster at build time.",
        "",
    ]

    for icon in icons:
        text = icon.read_text(encoding="utf-8")
        commands: list[str] = []
        for match in ELEMENT_RE.finditer(text):
            piece = element_to_path(match.group(1), match.group(2))
            if piece:
                commands.append(piece.strip())

        if not commands:
            print(f"skipping {icon.name}: no drawable elements", file=sys.stderr)
            continue

        parts.append(
            f"export component Icon{kebab(icon.stem)} inherits Path {{\n"
            f"    // Source: lucide `{icon.stem}`.\n"
            f"    commands: \"{' '.join(commands)}\";\n"
            f"    fill: transparent;\n"
            f"    stroke: transparent;\n"
            f"    stroke-width: 2px;\n"
            f"    stroke-line-cap: round;\n"
            f"    stroke-line-join: round;\n"
            f"}}\n"
        )

    target.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {len(icons)} icons to {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
