"""Render the Starpod mark (the Alliance emblem) into every icon the app ships.

Source: tools/icon/alliance.svg, a single filled path. Pillow cannot read SVG
and no SVG rasteriser is a project dependency, so the path is flattened here:
lines as they are, cubic curves as short segments, then filled at 8x and
scaled down for clean edges.

Writes:
  crates/starpod-ui/ui/assets/app-icon.png      256 px, the window icon
  crates/starpod-ui/ui/assets/tray-running.png  64 px, brand red
  crates/starpod-ui/ui/assets/tray-stopped.png  64 px, grey
  crates/starpod-app/assets/starpod.ico         16-256 px, the .exe icon
  crates/starpod-ui/ui/logo.slint               the in-app mark as a Slint Path

Run from the repository root:  python tools/render_icon.py
"""

import re
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "tools" / "icon" / "alliance.svg"
BRAND = (0xDE, 0x61, 0x61, 255)  # #de6161
STOPPED = (0x8A, 0x8A, 0x8F, 255)
SUPERSAMPLE = 8
# Share of the canvas the mark fills; the rest is a transparent margin.
FILL = 0.92


def read_source():
    text = SOURCE.read_text(encoding="utf-8")
    path = re.search(r'\sd="([^"]+)"', text).group(1)
    box = [float(v) for v in re.search(r'viewBox="([^"]+)"', text).group(1).split()]
    return " ".join(path.split()), box


def tokens(path):
    return re.findall(r"[MmLlHhVvCcZz]|-?(?:\d+\.?\d*|\.\d+)(?:e-?\d+)?", path)


def flatten(path, steps=24):
    """The path as a list of closed polygons, in source coordinates."""
    polys, current = [], []
    x = y = sx = sy = 0.0
    cmd = None
    items = tokens(path)
    i = 0

    def num():
        nonlocal i
        value = float(items[i])
        i += 1
        return value

    while i < len(items):
        if re.fullmatch(r"[A-Za-z]", items[i]):
            cmd = items[i]
            i += 1
            if cmd in "Zz":
                if current:
                    polys.append(current)
                current = []
                x, y = sx, sy
                continue
        rel = cmd.islower()
        c = cmd.upper()
        if c == "M":
            nx, ny = num(), num()
            x, y = (x + nx, y + ny) if rel else (nx, ny)
            if current:
                polys.append(current)
            current = [(x, y)]
            sx, sy = x, y
            cmd = "l" if rel else "L"  # further pairs are line-tos
        elif c == "L":
            nx, ny = num(), num()
            x, y = (x + nx, y + ny) if rel else (nx, ny)
            current.append((x, y))
        elif c == "H":
            nx = num()
            x = x + nx if rel else nx
            current.append((x, y))
        elif c == "V":
            ny = num()
            y = y + ny if rel else ny
            current.append((x, y))
        elif c == "C":
            pts = [num() for _ in range(6)]
            if rel:
                pts = [pts[k] + (x if k % 2 == 0 else y) for k in range(6)]
            x1, y1, x2, y2, x3, y3 = pts
            for s in range(1, steps + 1):
                t = s / steps
                mt = 1 - t
                px = mt**3 * x + 3 * mt * mt * t * x1 + 3 * mt * t * t * x2 + t**3 * x3
                py = mt**3 * y + 3 * mt * mt * t * y1 + 3 * mt * t * t * y2 + t**3 * y3
                current.append((px, py))
            x, y = x3, y3
        else:
            raise ValueError(f"unsupported path command {cmd}")
    if current:
        polys.append(current)
    return polys


def render(polys, box, size, colour):
    big = size * SUPERSAMPLE
    bx, by, bw, bh = box
    scale = big * FILL / max(bw, bh)
    ox = (big - bw * scale) / 2 - bx * scale
    oy = (big - bh * scale) / 2 - by * scale
    image = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    draw = ImageDraw.Draw(image)
    for poly in polys:
        draw.polygon([(px * scale + ox, py * scale + oy) for px, py in poly], fill=colour)
    return image.resize((size, size), Image.LANCZOS)


def slint_commands(path):
    """The path in Slint's `commands` syntax: commands and numbers, spaced."""
    return " ".join(tokens(path))


def write_logo(path, box):
    bx, by, bw, bh = box
    (ROOT / "crates" / "starpod-ui" / "ui" / "logo.slint").write_text(
        f"""// The Starpod mark: the Alliance emblem, in the brand red.
//
// The mark is the app's identity: the top bar, the sidebar and the window
// and tray icons. It lives in its own file because it is not a Lucide glyph.
//
// Generated by `tools/render_icon.py` from `tools/icon/alliance.svg`.
// Do not edit by hand.

export component StarpodMark inherits Path {{
    in property <color> tint: #de6161;
    commands: "{slint_commands(path)}";
    viewbox-x: {bx};
    viewbox-y: {by};
    viewbox-width: {bw};
    viewbox-height: {bh};
    fill: root.tint;
    stroke: transparent;
}}
""",
        encoding="utf-8",
    )


def main():
    path, box = read_source()
    polys = flatten(path)
    ui_assets = ROOT / "crates" / "starpod-ui" / "ui" / "assets"
    render(polys, box, 256, BRAND).save(ui_assets / "app-icon.png")
    render(polys, box, 64, BRAND).save(ui_assets / "tray-running.png")
    render(polys, box, 64, STOPPED).save(ui_assets / "tray-stopped.png")
    sizes = [16, 20, 24, 32, 40, 48, 64, 128, 256]
    frames = [render(polys, box, s, BRAND) for s in sizes]
    frames[-1].save(
        ROOT / "crates" / "starpod-app" / "assets" / "starpod.ico",
        sizes=[(s, s) for s in sizes],
        append_images=frames[:-1],
    )
    write_logo(path, box)
    print("wrote the icons and logo.slint")


if __name__ == "__main__":
    main()
